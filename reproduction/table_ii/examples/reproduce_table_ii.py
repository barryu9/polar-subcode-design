"""Construct the eight Table II codes in sequence and report process wall times."""

import argparse
import csv
from dataclasses import dataclass
import json
import os
from pathlib import Path
import platform
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]

sys.path.insert(0, str(ROOT / "python"))

from verify_independent_reproduction import EXPECTED, check

@dataclass(frozen=True)
class Case:
    key: str
    n: int
    k: int
    distance: int
    variant_identity: tuple[str, str] | None = None

    @property
    def expected(self):
        if self.variant_identity is not None:
            return self.variant_identity
        return EXPECTED[self.n, self.k]

CASES = (
    Case("n256_k64", 256, 64, 48),
    Case("n64_k32", 64, 32, 12),
    Case("n128_k64", 128, 64, 16),
    Case("n256_k128", 256, 128, 24),
    Case("n256_k171", 256, 171, 12),
    Case("n1024_k512", 1024, 512, 24),
    Case("n1024_k512_lm", 1024, 512, 24, (
        "ecfbc01086eac7222000064708f11f93987f3d30dc12be4a91753532e3d588c3",
        "3278f318e96958a1fd6aaf83dbca9a40c0f3b8a007764e1592517ccdaeb3a6a7",
    )),
    Case("n1024_k512_d32", 1024, 512, 32, (
        "8893007aa203bdfe4119d1744d06ad9c78e553b114dce039c61da50045bffc19",
        "3d2b101333fb39aa0907f9817bb5dfa83d525a788e3d5fd9fe4be9082bffb6cc",
    )),
)

TIMING_SCOPE = (
    "Elapsed wall time from launch of each Python construction process "
    "through its exit after saving the candidate archive. Includes startup, "
    "profile and expression construction, attempted candidates and limits, "
    "design-stage decoding and distance verification, and file I/O. "
    "Code identity comparison follows the timer. No independent FER "
    "evaluation or spectrum audit is part of the timer."
)

VARIANT_SCOPE = (
    "The two variants start from a checkpoint regenerated by n1024_k512 "
    "in the same suite. Their wall times each measure the additional "
    "construction after that shared run."
)

def write_json(path, value):
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")
    temporary.replace(path)

def save_report(folder, report):
    write_json(folder / "benchmark.json", report)
    fields = ("case", "N", "K", "target_distance", "status", "construction_wall_seconds",
              "shared_base_case", "archive_size", "code_path", "identity_check_seconds")
    temporary = folder / "timings.tmp"
    with temporary.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(report["results"])
    temporary.replace(folder / "timings.csv")

def run_case(case, folder, env):
    destination = folder / case.key
    script = ROOT / "examples" / f"reproduce_{case.key}.py"
    command = [sys.executable, "-u", str(script), "--output", str(destination),
               "--defer-acceptance"]
    log = folder / f"{case.key}.log"
    row = dict(case=case.key, N=case.n, K=case.k, target_distance=case.distance,
               command=command, log=str(log), status="failed")
    if case.variant_identity is not None:
        row["shared_base_case"] = "n1024_k512"
    print(f"Starting {case.key}; log: {log}", flush=True)
    with log.open("w", encoding="utf-8") as stream:
        # This interval covers the construction driver through saving its
        # candidate archive. The comparison with the plotted code below has
        # a separate timer so it can be identified in the timing record.
        start = time.perf_counter()
        process = subprocess.run(command, cwd=ROOT, env=env, stdout=stream,
                                 stderr=subprocess.STDOUT, check=False)
        row["construction_wall_seconds"] = time.perf_counter() - start
    row["returncode"] = process.returncode
    if process.returncode != 0:
        return row
    start = time.perf_counter()
    try:
        summary = json.loads((destination / "summary.json").read_text(encoding="utf-8"))
        if (summary["N"], summary["K"], summary["target"]) != (case.n, case.k, case.distance):
            raise ValueError("Construction archive parameters do not match the requested case")
        acceptance = check(destination, expected=case.expected, analyze_deductions=False)
        row.update(archive_size=acceptance["checked"],
                   acceptance=str(destination / "acceptance.json"))
        if acceptance["exact_pair_found"]:
            row.update(status="reproduced", code_path=acceptance["matching_pairs"][0]["code_path"])
        else:
            row["status"] = "target_absent"
    except (OSError, ValueError, KeyError, AssertionError) as error:
        row.update(status="acceptance_failed", error=str(error))
    row["identity_check_seconds"] = time.perf_counter() - start
    return row

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="Fresh report directory (default: timestamped)")
    parser.add_argument("--cases", nargs="+", choices=[case.key for case in CASES],
                        help="Construct only the selected codes")
    args = parser.parse_args()
    folder = (args.output or ROOT / "results" /
              f"table_ii_wall_time_{time.strftime('%Y%m%d_%H%M%S')}").resolve()
    folder.mkdir(parents=True, exist_ok=False)
    selected = set(args.cases) if args.cases is not None else {case.key for case in CASES}
    if any(case.key in selected and case.variant_identity is not None for case in CASES):
        # Proposed-LM and Proposed-D32 continue from a freshly constructed
        # length-1024 code. Run that shared stage once for the selected suite.
        selected.add("n1024_k512")
    cases = [case for case in CASES if case.key in selected]
    threads = dict.fromkeys(("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS"), "1")
    env = {**os.environ, **threads}
    report = dict(timing_scope=TIMING_SCOPE, variant_timing_scope=VARIANT_SCOPE,
                  sequential=True, python=sys.version,
                  platform=platform.platform(), processor=platform.processor(),
                  logical_processors=os.cpu_count(), thread_settings=threads,
                  cases=[case.key for case in cases], results=[])
    save_report(folder, report)
    results_by_key = {}
    for case in cases:
        if case.variant_identity is not None and results_by_key["n1024_k512"]["status"] != "reproduced":
            row = dict(case=case.key, N=case.n, K=case.k,
                       target_distance=case.distance, shared_base_case="n1024_k512",
                       status="dependency_failed")
        else:
            row = run_case(case, folder, env)
        results_by_key[case.key] = row
        report["results"].append(row)
        save_report(folder, report)
        elapsed = row.get("construction_wall_seconds")
        duration = "" if elapsed is None else f", {elapsed:.3f} s"
        print(f'{case.key}: {row["status"]}{duration}', flush=True)
    return 0 if all(row["status"] == "reproduced" for row in report["results"]) else 1

if __name__ == "__main__":
    raise SystemExit(main())
